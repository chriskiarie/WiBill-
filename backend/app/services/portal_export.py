def _generate_inline_css(theme: dict, typography: dict, card: dict, animations: dict) -> str:
    primary = theme.get("primary_color", "#E8B84B")
    secondary = theme.get("secondary_color", "#1a1a2e")
    accent = theme.get("accent_color", "#00d4aa")
    bg_value = theme.get("background_value", "#0a0a0a")
    bg_type = theme.get("background_type", "solid")
    gradient = theme.get("gradient", "")
    overlay = theme.get("overlay_color", "#000000")
    overlay_opacity = theme.get("overlay_opacity", 0.3)
    button_style = theme.get("button_style", "rounded")

    ff = typography.get("font_family", "Inter")
    heading_size = typography.get("heading_size", 32)
    body_size = typography.get("body_size", 15)
    font_weight = typography.get("font_weight", 500)
    letter_spacing = typography.get("letter_spacing", 0.3)

    card_style = card.get("style", "glass")
    card_radius = card.get("radius", 12)

    btn_radius = {"rounded": "12px", "pill": "24px", "sharp": "0px"}.get(button_style, "12px")

    bg_css = f"background: {bg_value};"
    if bg_type == "gradient" and gradient:
        bg_css = f"background: {gradient};"
    if bg_type in ("image", "video"):
        bg_css = "background: #000;"

    entrance = animations.get("entrance", "fade-in")
    anim_css = ""
    if entrance == "slide-up":
        anim_css = "@keyframes slideUp { from { opacity: 0; transform: translateY(30px); } to { opacity: 1; transform: translateY(0); } }"
    elif entrance == "zoom":
        anim_css = "@keyframes zoomIn { from { opacity: 0; transform: scale(0.95); } to { opacity: 1; transform: scale(1); } }"
    elif entrance == "fade-in":
        anim_css = "@keyframes fadeIn { from { opacity: 0; } to { opacity: 1; } }"

    return f"""/* Portal Studio Generated Styles */
* {{ margin: 0; padding: 0; box-sizing: border-box; }}
body {{ {bg_css} color: #fff; font-family: '{ff}', sans-serif; font-size: {body_size}px; font-weight: {font_weight}; letter-spacing: {letter_spacing}px; min-height: 100vh; }}
.portal-root {{ position: relative; min-height: 100vh; }}
.portal-overlay {{ position: fixed; inset: 0; background: {overlay}; opacity: {overlay_opacity}; pointer-events: none; z-index: 0; }}
.portal-container {{ position: relative; z-index: 1; max-width: 480px; margin: 0 auto; padding: 40px 20px; animation: fadeIn 0.6s ease-out; }}
{anim_css}
.portal-header {{ text-align: center; margin-bottom: 40px; }}
.portal-emoji {{ font-size: 48px; display: block; margin-bottom: 12px; }}
.portal-name {{ font-size: {heading_size}px; font-weight: {font_weight + 100}; color: {primary}; margin-bottom: 8px; }}
.portal-tagline {{ font-size: {body_size}px; color: rgba(255,255,255,0.7); margin-bottom: 4px; }}
.portal-location {{ font-size: {body_size - 2}px; color: rgba(255,255,255,0.5); }}
.packages-container {{ margin: 30px 0; }}
.portal-footer {{ text-align: center; margin-top: 40px; padding: 20px; }}
.portal-link {{ display: inline-block; padding: 12px 24px; background: {primary}; color: #000; border-radius: {btn_radius}; text-decoration: none; font-weight: 600; }}
.packages-placeholder {{ text-align: center; color: rgba(255,255,255,0.4); font-style: italic; }}
h1, h2, h3 {{ font-family: '{ff}', sans-serif; }}
"""


def _generate_inline_js(components: dict, animations: dict, portal_url: str) -> str:
    return f"""// Portal Studio Generated
(function() {{
    var root = document.getElementById('portal-root');
    if (root) {{
        root.classList.add('portal-root');
        var overlay = document.createElement('div');
        overlay.className = 'portal-overlay';
        root.prepend(overlay);
    }}
    console.log('HonestBill Portal v2 | Live: {portal_url}');
}})();
"""


