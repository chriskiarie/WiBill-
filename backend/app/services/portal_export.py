"""Export service: MikroTik ZIP bundle and QR poster generation."""

import io
import zipfile
import json
from pathlib import Path
from typing import Optional

TEMPLATES_DIR = Path(__file__).resolve().parent.parent / "templates"


def generate_mikrotik_zip(
    portal_config: dict,
    brand_name: str,
    slug: str,
    logo_b64: str | None = None,
    background_b64: str | None = None,
) -> io.BytesIO:
    buf = io.BytesIO()
    template_id = portal_config.get("template_id", "spotlight")
    theme = portal_config.get("theme", {})
    typography = portal_config.get("typography", {})
    brand = portal_config.get("brand", {})
    card = portal_config.get("card", {})
    components = portal_config.get("components", {})
    animations = portal_config.get("animations", {})

    base_template = _get_base_template_file(template_id)
    base_html = ""
    if base_template and base_template.exists():
        base_html = base_template.read_text(encoding="utf-8")

    portal_url = f"https://portal.honestbill.co.ke/portal/{slug}"

    inline_css = _generate_inline_css(theme, typography, card, animations)
    inline_js = _generate_inline_js(components, animations, portal_url)

    if "{{" in base_html or "{%" in base_html:
        html = base_html
    else:
        html = _build_standalone_html(base_html, brand, inline_css, inline_js, portal_url)

    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("index.html", html)
        zf.writestr("style.css", inline_css)
        zf.writestr("script.js", inline_js)
        zf.writestr("portal_config.json", json.dumps(portal_config, indent=2))

        if logo_b64:
            import base64
            try:
                logo_data = base64.b64decode(logo_b64)
                zf.writestr("images/logo.png", logo_data)
            except Exception:
                pass

        if background_b64:
            import base64
            try:
                bg_data = base64.b64decode(background_b64)
                zf.writestr("images/background.png", bg_data)
            except Exception:
                pass

        readme = f"""=== {brand_name} Portal Offline Package ===

Deploy to MikroTik:
1. Open WinBox
2. Navigate to Files
3. Drag this ZIP onto the router
4. Extract (Files > Extract)
5. Set hotspot login page to index.html

Portal URL (online): {portal_url}

Generated by HonestBill Portal Studio
"""
        zf.writestr("README.txt", readme)

    buf.seek(0)
    return buf


